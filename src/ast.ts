export type Id = { type: 'id'; text: string; loc: Loc };

export type Pat = (
    | Id
    | { type: 'bool'; value: boolean; loc: Loc }
    | { type: 'number'; value: number; loc: Loc }
    | { type: 'drop'; loc: Loc }
    | { type: 'tuple'; items: Pat[]; loc: Loc }
    | { type: 'constructor'; name: string; args: Pat[]; loc: Loc }
    /** Exhaustive record pattern; field order is source order, never significant. */
    | { type: 'record'; fields: { name: string; pat: Pat; loc: Loc }[]; loc: Loc }
    | { type: 'string'; text: string; loc: Loc }
    // | { type: 'list'; items: Pat[]; tail?: Pat; loc: Loc }
    | { type: 'lens'; inner: Pat; loc: Loc }
) & {
    /** Internal link from a selected owned pattern to its reconstruction target. */ reconstructionOwner?: Id;
};

export type Loc = number;

export type Type =
    | Id
    /**
     * `~A` is `A/A`; `=A` is `A/=A`. `replaceable: false` marks a lens whose whole value
     * cannot be replaced (a constructor of borrowed fields); absent means replaceable.
     */
    | { type: 'lens'; left: Type; right?: Type; replaceable?: boolean }
    | { type: 'constr'; name: Id; args?: Type[]; loc: Loc }
    | { type: 'tuple'; items: Type[] }
    | { type: 'record'; fields: { name: string; type: Type; loc: Loc }[]; loc: Loc }
    | { type: 'fn'; args: Type[]; body: Type };

export type TypeDecl =
    | { type: 'type-alias'; name: Id; alias: Type; loc: Loc; args?: Id[]; linear?: boolean }
    | { type: 'union'; name: Id; args?: Id[]; items: TypeConstr[]; loc: Loc; linear?: boolean };
export type TypeConstr = { name: Id; loc: Loc; args?: Type[] };

export type File = FileItem[];
export type FileItem = Linear | Decl | TypeDecl;
export type Decl = { type: 'decl'; name: Id; ann: Type; loc: number };

export type Lens =
    | Id
    | {
          type: 'aslens';
          pat: Pat;
          value: Linear;
          body: Linear;
          loc: Loc;
          reconstructionPattern?: Pat;
      }
    | {
          type: 'let';
          pat: Pat;
          value: Term;
          body: Lens;
          loc: Loc;
          borrowedOwner?: boolean;
          mut?: boolean;
      }
    | { type: 'apply'; fn: Linear; args: Term[]; share?: boolean; loc: Loc }
    /** Field `name` of the record focused by `target`. */
    | { type: 'field'; target: Lens; name: string; loc: Loc }
    /** Element `index` of the vector focused by `target`. */
    | { type: 'index'; target: Lens; index: Term; loc: Loc }
    | { type: 'tuple'; items: Lens[]; loc: Loc }
    /**
     * A constructor of lenses. Not a lens to a stored value: over a multi-constructor
     * type it is not replaceable as a whole (see docs/scattered-constructor-lenses.md).
     */
    | { type: 'constructor'; name: string; args: Lens[]; loc: Loc }
    | { type: 'case'; value: Term; cases: { pat: Pat; body: Lens; mut?: boolean }[]; loc: Loc };

export type Term = Linear | { type: 'lens'; lens: Lens };

export type LinearCase = { pat: Pat; body: Linear; mut?: boolean };
export type LensCase = { pat: Pat; body: Lens; mut?: boolean };

export type LinearOps =
    | { type: 'index'; index: Term }
    | { type: 'apply'; args: Term[] }
    // `r.x` lexes as `r`, `.`, `x`; handleSuffixes pairs a dot with the name after it.
    | { type: 'dot' }
    | { type: 'name'; text: string };

export type LensOp =
    | { type: 'index'; index: Term }
    | { type: 'dot' }
    | { type: 'name'; text: string };

export type Op = { type: 'op'; text: string; loc: Loc };
/** `mut` (dual mode) makes the parameter exclusive and lensable; otherwise it is plain. */
/**
 * `shared` is set by the dual-mode desugar on a plain parameter, whose value is shared and
 * immutable. A pure parameter is never shared.
 */
export type FnArg = { pat: Pat; typ?: Type; mut?: boolean; shared?: boolean };
export type LinearInterp = { value: Linear; tail: string };

export type Linear =
    | Id
    | Op
    | { type: 'assign'; lens: Lens; value: Linear; loc: Loc }
    | { type: 'number'; value: number; loc: Loc }
    | { type: 'bool'; value: boolean; loc: Loc }
    | {
          type: 'string';
          head: string;
          interp: { value: Linear; tail: string }[];
          loc: Loc;
      }
    // unlens???
    /** `borrowedOwner`: generated by `normalizeBorrowed` to name the lens a match borrows. */
    | {
          type: 'let';
          pat: Pat;
          value: Term;
          body: Linear;
          loc: Loc;
          borrowedOwner?: boolean;
          mut?: boolean;
      }
    | {
          type: 'fn';
          name?: string | null;
          args: FnArg[];
          ann?: Type | null;
          body: Term;
          loc: Loc;
      }
    | { type: 'index'; target: Linear; index: Term; loc: Loc }
    /** Move field `name` out of a variable's record: `r.x`, `r.a.b`. */
    | { type: 'field'; target: Linear; name: string; loc: Loc }
    | { type: 'apply'; fn: Linear; args: Term[]; isLens?: boolean; share?: boolean; loc: Loc }
    | { type: 'tuple'; items: Linear[]; loc: Loc }
    | { type: 'vector'; items: Linear[]; loc: Loc }
    | { type: 'record'; fields: { name: string; value: Linear; loc: Loc }[]; loc: Loc }
    | { type: 'constructor'; name: string; args: Linear[]; loc: Loc }
    | { type: 'case'; value: Term; cases: { pat: Pat; body: Linear; mut?: boolean }[]; loc: Loc };

export const names = (pat: Pat): string[] => {
    switch (pat.type) {
        case 'id':
            return [pat.text];
        case 'number':
        case 'drop':
        case 'bool':
        case 'string':
            return [];
        // case 'list':
        //     return pat.items.flatMap(names).concat(pat.tail ? names(pat.tail) : []);
        case 'tuple':
            return pat.items.flatMap(names);
        case 'constructor':
            return pat.args.flatMap(names);
        case 'record':
            return pat.fields.flatMap((f) => names(f.pat));
        case 'lens':
            return names(pat.inner);
    }
};

export const free = (expr: Term | Lens): string[] => {
    switch (expr.type) {
        case 'aslens': {
            const one = free(expr.value);
            const bound = names(expr.pat);
            const two = free(expr.body);
            return one.concat(two.filter((t) => !one.includes(t) && !bound.includes(t)));
        }
        case 'string': {
            let res: string[] = [];
            expr.interp.forEach((item) => {
                free(item.value).forEach((name) => {
                    if (!res.includes(name)) res.push(name);
                });
            });
            return res;
        }
        case 'id':
        case 'op':
            return [expr.text];
        case 'bool':
        case 'number':
            return [];
        case 'let': {
            const one = free(expr.value);
            const bound = names(expr.pat);
            const two = free(expr.body);
            return one.concat(two.filter((t) => !one.includes(t) && !bound.includes(t)));
        }
        case 'case': {
            const res = free(expr.value);
            expr.cases.forEach((kase) => {
                const bound = names(kase.pat);
                free(kase.body)
                    .filter((t) => !bound.includes(t))
                    .forEach((name) => {
                        if (!res.includes(name)) res.push(name);
                    });
            });
            return res;
        }
        // case "additive_product":
        //     throw new Error("not uet");
        case 'vector':
        case 'tuple':
            return expr.items.flatMap(free);
        // case "ifs":
        //     throw new Error("nop");
        case 'fn': {
            const bound = expr.args.flatMap((arg) => names(arg.pat));
            return free(expr.body).filter((t) => !bound.includes(t));
        }
        case 'apply': {
            return free(expr.fn).concat(expr.args.flatMap(free));
        }
        case 'index':
            return free(expr.target).concat(free(expr.index));
        case 'field':
            return free(expr.target);
        case 'lens':
            return free(expr.lens);
        case 'constructor': {
            return expr.args.flatMap(free);
        }
        case 'record':
            return expr.fields.flatMap((f) => free(f.value));
        case 'assign': {
            return free(expr.value).concat(free(expr.lens));
        }
    }
};

export const getFree = (
    bound: Set<string>,
    expr: Term | Lens,
    ref: Set<string>,
    deref: Set<string>,
) => {
    switch (expr.type) {
        case 'aslens': {
            getFree(bound, expr.value, ref, deref);
            const lbound = names(expr.pat);
            getFree(bound.union(new Set(lbound)), expr.body, ref, deref);
            return;
        }
        case 'string': {
            expr.interp.forEach((item) => {
                getFree(bound, item.value, ref, deref);
            });
            return;
        }
        case 'id':
        case 'op':
            if (!bound.has(expr.text)) ref.add(expr.text);
            return;
        case 'bool':
        case 'number':
            return;
        case 'let': {
            getFree(bound, expr.value, ref, deref);
            const lbound = names(expr.pat);
            getFree(bound.union(new Set(lbound)), expr.body, ref, deref);
            return;
        }
        case 'case': {
            getFree(bound, expr.value, ref, deref);
            expr.cases.forEach((kase) => {
                const lbound = names(kase.pat);
                getFree(bound.union(new Set(lbound)), kase.body, ref, deref);
            });
            return;
        }
        // case "additive_product":
        //     throw new Error("not uet");
        case 'vector':
        case 'tuple':
            expr.items.forEach((item) => getFree(bound, item, ref, deref));
            return;
        case 'index':
            getFree(bound, expr.target, ref, deref);
            getFree(bound, expr.index, ref, deref);
            return;
        case 'field':
            getFree(bound, expr.target, ref, deref);
            return;
        // case "ifs":
        //     throw new Error("nop");
        case 'fn': {
            const lbound = expr.args.flatMap((arg) => names(arg.pat));
            getFree(bound.union(new Set(lbound)), expr.body, ref, deref);
            return;
        }
        case 'apply': {
            getFree(bound, expr.fn, ref, deref);
            expr.args.forEach((item) => getFree(bound, item, ref, deref));
            return;
        }
        case 'lens': {
            const ign = new Set<string>();
            getFree(bound, expr.lens, deref, ign);
            if (ign.size) {
                // console.log(deref, ign);
                console.warn('lens has derefs?');
            }
            return;
        }
        case 'constructor': {
            expr.args.forEach((item) => getFree(bound, item, ref, deref));
            return;
        }
        case 'record':
            expr.fields.forEach((f) => getFree(bound, f.value, ref, deref));
            return;
        case 'assign': {
            getFree(bound, expr.value, ref, deref);
            getFree(bound, expr.lens, deref, new Set());
            return;
        }
    }
};

export type TypeField = { name: string; type: Type; loc: Loc };
export type PatField = { name: string; pat: Pat; loc: Loc };
export type RecordField = { name: string; value: Linear; loc: Loc };
